/** 
******************************************************************************* 
** \brief BGR enable 
** 
** 
** \retval Null 
*******************************************************************************/
void Bgr_BgrEnable(void)
{    
    M0P_BGR->CR |= 0x1u;
    
    delay10us(2);
}

/** 
******************************************************************************* 
** \brief BGR disable 
** 
** 
** \retval Null 
*******************************************************************************/
void Bgr_BgrDisable(void)
{
    M0P_BGR->CR &= 0x2u;
}

/** *****************************************************************************
** \brief BGR temperature sensor enable (need to enable BGR first)
**
**
** \retval Null
*************************************************************************/
void Bgr_TempSensorEnable(void)
{
    M0P_BGR->CR |= 0x2u;
    
    delay10us(2);  
}

/**
*************************************************************************
** \brief BGR temperature sensor disable
**
**
** \retval Null
*************************************************************************/
void Bgr_TempSensorDisable(void)
{
    M0P_BGR->CR &= 0x1u;
}


